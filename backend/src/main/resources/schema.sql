
CREATE TABLE IF NOT EXISTS customer (
        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name        VARCHAR(255) NOT NULL,
        email       VARCHAR(255),
        phone       VARCHAR(50),
        street      VARCHAR(255),
        zip_code    VARCHAR(10),
        city        VARCHAR(255),
        created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS product (
       id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
       sku           VARCHAR(50)  NOT NULL UNIQUE,
       name          VARCHAR(255) NOT NULL,
       description   VARCHAR(255),
       unit          VARCHAR(20)  NOT NULL,
       quantity      INTEGER      NOT NULL DEFAULT 0 CHECK (quantity >= 0),
       min_quantity  INTEGER      NOT NULL DEFAULT 0 CHECK (min_quantity >= 0),
       image_url     VARCHAR(500),
       version       BIGINT       NOT NULL DEFAULT 0,
       created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
       updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS inbound_delivery (
        id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        delivery_number  VARCHAR(20)  UNIQUE,
        supplier_name    VARCHAR(255) NOT NULL,
        status           VARCHAR(20)  NOT NULL CHECK (status IN ('DRAFT', 'CONFIRMED', 'CANCELLED')),
        delivery_date    DATE         NOT NULL DEFAULT CURRENT_DATE,
        note             VARCHAR(255),
        created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS inbound_delivery_item (
     id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     inbound_delivery_id  BIGINT  NOT NULL,
     product_id           BIGINT  NOT NULL,
     quantity             INTEGER NOT NULL CHECK (quantity > 0),
     CONSTRAINT fk_inbound_delivery_item_inbound_delivery FOREIGN KEY (inbound_delivery_id) REFERENCES inbound_delivery (id),
     CONSTRAINT fk_inbound_delivery_item_product          FOREIGN KEY (product_id) REFERENCES product (id),
     CONSTRAINT uq_inbound_delivery_item_product          UNIQUE (inbound_delivery_id, product_id)
);

CREATE TABLE IF NOT EXISTS outbound_order (
      id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      order_number  VARCHAR(20) UNIQUE,
      customer_id   BIGINT      NOT NULL,
      status        VARCHAR(20) NOT NULL CHECK (status IN ('DRAFT', 'CONFIRMED', 'CANCELLED')),
      order_date    DATE        NOT NULL DEFAULT CURRENT_DATE,
      note          VARCHAR(255),
      created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
      CONSTRAINT fk_outbound_order_customer FOREIGN KEY (customer_id) REFERENCES customer (id)
);

CREATE TABLE IF NOT EXISTS outbound_order_item (
       id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
       outbound_order_id  BIGINT  NOT NULL,
       product_id         BIGINT  NOT NULL,
       quantity           INTEGER NOT NULL CHECK (quantity > 0),
       CONSTRAINT fk_outbound_order_item_outbound_order FOREIGN KEY (outbound_order_id) REFERENCES outbound_order (id),
       CONSTRAINT fk_outbound_order_item_product        FOREIGN KEY (product_id) REFERENCES product (id),
       CONSTRAINT uq_outbound_order_item_product        UNIQUE (outbound_order_id, product_id)
);